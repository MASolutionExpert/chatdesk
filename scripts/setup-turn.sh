#!/usr/bin/env bash
# ChatDesk — deploy a coturn (TURN/STUN) relay for 10/10 call quality.
#
# STUN alone connects most peers, but peers behind symmetric NAT (many mobile
# carriers, corporate networks) can ONLY connect through a TURN relay. Without
# TURN those calls never connect; with TURN, ~every call connects and ICE can
# pick the fastest usable path (host < srflx < relay). This script installs and
# configures coturn on the same host as ChatDesk and wires the credentials
# into the ChatDesk .env.
#
# Run as root on the ChatDesk server:
#   bash scripts/setup-turn.sh                 # install + configure + wire .env
#   bash scripts/setup-turn.sh --print-only    # only print the env lines
#
# After running, restart ChatDesk so the server picks up the new env:
#   systemctl restart chatdesk   (or your service manager equivalent)

set -euo pipefail

PRINT_ONLY=0
[[ "${1:-}" == "--print-only" ]] && PRINT_ONLY=1

if [[ $PRINT_ONLY -eq 0 && $EUID -ne 0 ]]; then
  echo "setup-turn: run as root (sudo bash scripts/setup-turn.sh)" >&2
  exit 1
fi

# ── Locate the ChatDesk install dir (for the .env) ────────────────────────────
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ENV=""
if [[ -f "$SCRIPT_DIR/../.env" ]]; then
  REPO_ENV="$(cd "$SCRIPT_DIR/.." && pwd)/.env"
fi
# The installer installs into /var/www/chatdesk by default; prefer its .env.
INSTALL_ENV="/var/www/chatdesk/.env"
if [[ -f "$INSTALL_ENV" ]]; then
  ENV_FILE="$INSTALL_ENV"
elif [[ -n "$REPO_ENV" ]]; then
  ENV_FILE="$REPO_ENV"
else
  ENV_FILE=""
fi

# ── Detect the public IPv4 ────────────────────────────────────────────────────
PUBLIC_IP="$(curl -4 -fsS --max-time 5 https://api.ipify.org 2>/dev/null \
  || curl -4 -fsS --max-time 5 https://ifconfig.me 2>/dev/null \
  || echo "")"
if [[ -z "$PUBLIC_IP" ]]; then
  echo "setup-turn: could not detect the public IP; pass it via PUBLIC_IP=... env" >&2
  exit 1
fi

TURN_USER="chatdesk"
TURN_PASS="$(openssl rand -hex 16 2>/dev/null || head -c 16 /dev/urandom | od -An -tx1 | tr -d ' \n')"
RELAY_MIN=49152
RELAY_MAX=65535

if [[ $PRINT_ONLY -eq 1 ]]; then
  cat <<EOF
TURN_URL="turn:${PUBLIC_IP}:3478?transport=udp"
TURN_USERNAME="${TURN_USER}"
TURN_CREDENTIAL="${TURN_PASS}"
EOF
  exit 0
fi

echo "==> Installing coturn..."
if command -v apt-get >/dev/null 2>&1; then
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq
  apt-get install -y -qq coturn
elif command -v dnf >/dev/null 2>&1; then
  dnf install -y coturn
elif command -v yum >/dev/null 2>&1; then
  yum install -y coturn
else
  echo "setup-turn: unsupported package manager; install coturn manually and re-run." >&2
  exit 1
fi

echo "==> Writing /etc/turnserver.conf..."
install -m 0644 /dev/null /etc/turnserver.conf
cat > /etc/turnserver.conf <<EOF
# Generated by ChatDesk scripts/setup-turn.sh
listening-port=3478
# NOTE: no listening-ip on purpose. On NAT'd cloud VMs the detected public IP
# is not bound to an interface, so coturn would fail to bind. Let coturn bind
# to all interfaces and use external-ip for the advertised address.
external-ip=${PUBLIC_IP}
min-port=${RELAY_MIN}
max-port=${RELAY_MAX}
# Long-term credentials (matches ChatDesk's TURN_USERNAME/TURN_CREDENTIAL env)
lt-cred-mech
user=${TURN_USER}:${TURN_PASS}
realm=chatdesk
# Relay targets: never allow peers on internal / infrastructure networks.
# Without these ranges any client holding the shared credential could relay
# into the host's private network or the cloud metadata endpoint
# (169.254.169.254) — an open proxy into internal services.
# IPv4 reserved / private ranges:
denied-peer-ip=0.0.0.0-0.255.255.255
denied-peer-ip=10.0.0.0-10.255.255.255
denied-peer-ip=100.64.0.0-100.127.255.255
denied-peer-ip=127.0.0.0-127.255.255.255
denied-peer-ip=169.254.0.0-169.254.255.255
denied-peer-ip=172.16.0.0-172.31.255.255
denied-peer-ip=192.168.0.0-192.168.255.255
# IPv6 unique-local, link-local and IPv4-mapped equivalents:
denied-peer-ip=fc00::-fdff:ffff:ffff:ffff:ffff:ffff:ffff:ffff
denied-peer-ip=fe80::-febf:ffff:ffff:ffff:ffff:ffff:ffff:ffff
denied-peer-ip=::ffff:0:0-::ffff:ffff:ffff
# Belt-and-braces: coturn built-in peer filters.
no-loopback-peers
no-multicast-peers
# Security & performance
no-cli
fingerprint
# Logging (system journal)
simple-log
EOF

echo "==> Enabling coturn service..."
systemctl enable coturn >/dev/null 2>&1 || true
systemctl restart coturn

# Allow the media ports through the firewall when one is active.
if command -v ufw >/dev/null 2>&1 && ufw status | grep -q "Status: active"; then
  echo "==> Opening firewall ports (3478, ${RELAY_MIN}-${RELAY_MAX}/udp)..."
  ufw allow 3478/tcp  >/dev/null 2>&1 || true
  ufw allow 3478/udp  >/dev/null 2>&1 || true
  ufw allow ${RELAY_MIN}:${RELAY_MAX}/udp >/dev/null 2>&1 || true
fi
if command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --state >/dev/null 2>&1; then
  echo "==> Opening firewall ports (3478, ${RELAY_MIN}-${RELAY_MAX}/udp)..."
  firewall-cmd --permanent --add-port=3478/tcp >/dev/null 2>&1 || true
  firewall-cmd --permanent --add-port=3478/udp >/dev/null 2>&1 || true
  firewall-cmd --permanent --add-port=${RELAY_MIN}-${RELAY_MAX}/udp >/dev/null 2>&1 || true
  firewall-cmd --reload >/dev/null 2>&1 || true
fi

# ── Wire the credentials into the ChatDesk .env ───────────────────────────────
# A non-empty existing TURN_URL always wins (never rotate a working relay).
write_env_line() {
  local key="$1" value="$2" env_file="$3"
  if grep -qE "^${key}=" "$env_file"; then
    # Replace only when the current value is empty ("KEY=" or 'KEY=""')
    sed -i "s|^${key}=.\{0,3\}$|${key}=\"${value}\"|" "$env_file" || true
    if ! grep -qE "^${key}=\"?.+\"?$" "$env_file"; then
      sed -i "s|^${key}=.*|${key}=\"${value}\"|" "$env_file"
    fi
  else
    printf '%s="%s"\n' "$key" "$value" >> "$env_file"
  fi
}

if [[ -n "$ENV_FILE" ]]; then
  echo "==> Wiring credentials into $ENV_FILE ..."
  write_env_line "TURN_URL" "turn:${PUBLIC_IP}:3478?transport=udp" "$ENV_FILE"
  write_env_line "TURN_USERNAME" "$TURN_USER" "$ENV_FILE"
  write_env_line "TURN_CREDENTIAL" "$TURN_PASS" "$ENV_FILE"
  echo "==> Done. Restart ChatDesk to pick up the new env:"
  echo "    systemctl restart chatdesk"
else
  echo "==> Could not locate a ChatDesk .env; add these lines manually:"
  echo 'TURN_URL="turn:'"${PUBLIC_IP}"':3478?transport=udp"'
  echo 'TURN_USERNAME="'"${TURN_USER}"'"'
  echo 'TURN_CREDENTIAL="'"${TURN_PASS}"'"'
fi

echo ""
echo "TURN relay ready: ${PUBLIC_IP}:3478 (relay ports ${RELAY_MIN}-${RELAY_MAX}/udp)"
echo "Verify it is listening:  systemctl status coturn"
